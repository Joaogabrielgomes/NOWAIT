CREATE TABLE estabelecimentos (
    id                              CHAR(36)     NOT NULL DEFAULT (UUID()),
    usuario_id                      CHAR(36)     NOT NULL,
    nome                            VARCHAR(150) NOT NULL,
    categoria                       VARCHAR(30)  NOT NULL,
    telefone                        VARCHAR(20)  NOT NULL,
    cep                             VARCHAR(9)   NOT NULL,
    logradouro                      VARCHAR(150) NOT NULL,
    numero                          VARCHAR(10)  NOT NULL,
    complemento                     VARCHAR(100) NULL,
    bairro                          VARCHAR(100) NOT NULL,
    cidade                          VARCHAR(100) NOT NULL,
    estado                          VARCHAR(2)   NOT NULL,
    tempo_medio_atendimento_minutos INT          NOT NULL DEFAULT 15,
    tolerancia_padrao_minutos       INT          NOT NULL DEFAULT 15,
    horario_abertura                TIME         NOT NULL DEFAULT '08:00:00',
    horario_fechamento              TIME         NOT NULL DEFAULT '22:00:00',
    antecedencia_maxima_dias        INT          NOT NULL DEFAULT 7,
    antecedencia_reserva_mesa_minutos INT        NOT NULL DEFAULT 15,
    antecedencia_minima_minutos     INT          NOT NULL DEFAULT 30,
    aberto                          BOOLEAN      NOT NULL DEFAULT TRUE,
    status_aprovacao                VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    motivo_rejeicao                 VARCHAR(500) NULL,
    token_contestacao_rejeicao      CHAR(36)     NULL,
    logo_url                        VARCHAR(255) NULL,
    banner_url                      VARCHAR(255) NULL,
    created_at                      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT pk_estabelecimentos            PRIMARY KEY (id),
    CONSTRAINT uq_estabelecimentos_usuario_id UNIQUE (usuario_id),
    CONSTRAINT fk_estabelecimentos_usuario    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
